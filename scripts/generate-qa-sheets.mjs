function esc(cell) {
  const s = String(cell ?? '');
  if (s.includes(',') || s.includes('"') || s.includes('\n')) {
    return `"${s.replace(/"/g, '""')}"`;
  }
  return s;
}

function toCsv(rows) {
  const bom = '\uFEFF';
  return bom + rows.map((row) => row.map(esc).join(',')).join('\n');
}

